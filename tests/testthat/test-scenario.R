test_that("the default scenario is usable without arguments", {
  s <- movesr_scenario()
  expect_s3_class(s, "movesr_scenario")
  expect_equal(s$year, 2025)
  expect_equal(s$source_type_id, 21)
  expect_equal(s$fuel_type_id, 1)
  expect_equal(s$model_year, 2020)
  expect_equal(s$pollutant_id, 3)
  expect_equal(s$process_id, 1)
  expect_equal(s$road_type_id, 5)
  expect_equal(s$temperature_c, 20)
  expect_equal(s$rel_humidity, 50)
  expect_equal(s$hour_id, 1)
})
